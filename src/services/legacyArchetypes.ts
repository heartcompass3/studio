export const getLegacyArchetype = (id = 'belief_choice'): LegacyArchetype =>
  HOOK_ARCHETYPES.find(item => item.id === id) || HOOK_ARCHETYPES[0];

const beatTypes: ScriptBeat['type'][] = ['hook', 'mirror', 'internal', 'reversal', 'action'];
export const getLegacyBeatSchema = (id: string) =>
  getLegacyArchetype(id).stages.map((item, index) => ({
    id: beatTypes[index], type: beatTypes[index], title: item.title, text: item.task,
  }));

