export function splitLegacyScript(text: string): ScriptBeat[] {
  const defaultTitles = [
    'הוק עוצר גלילה',
    'גשר אמפתיה ומיקוד',
    'ההבחנה המרכזית (ערך 1)',
    'ריהוק שומר קשב',
    'צעד מעשי להיום (ערך 2)',
    'הנעה לפעולה ולידים (CTA)'
  ];
  return text.split(/\n\s*\n/).filter(p => p.trim()).map((paragraph, index) => ({
    id: beatTypes[index] || `beat-${index + 1}`,
    type: beatTypes[index] || 'action',
    title: defaultTitles[index] || `תחנה ${index + 1}`,
    text: paragraph.trim(),
  }));
}
