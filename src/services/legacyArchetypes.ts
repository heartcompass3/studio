// Imported or manually edited text retains every paragraph without invented stage roles.
export function splitLegacyScript(text: string): ScriptBeat[] {
  return text.split(/\n\s*\n/).filter(p => p.trim()).map((paragraph, index) => ({
    id: `paragraph_${index}`, type: index === 0 ? 'hook' : 'mirror',
    title: index === 0 ? 'פתיחה' : `מקטע ${index + 1}`, text: paragraph.trim(),
  }));
}
